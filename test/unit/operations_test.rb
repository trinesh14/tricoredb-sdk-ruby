  CASES.each do |name, op, reply, txn, call|
    define_method("test_#{name}_sends_the_operation_the_server_declares") do
      seen = nil
      script = lambda do |peer|
        peer.handshake
        _tag, seen = peer.read
        peer.send_frame(TriCoreDB::Frame::RESPONSE,
                        { "request_id" => "r1", "status" => "ok", "data" => JSON.parse(reply) })
        begin
          peer.read
        rescue StandardError, IOError
          nil
        end
      end

      ScriptedPeer.run(script) { |db| call.call(db) }

      assert_equal JSON.parse(op), seen["op"]
      assert_equal "main", seen["database"]
      if txn.nil?
        assert_nil seen.dig("options", "txn")
      else
        assert_equal txn, seen.dig("options", "txn")
      end
    end
  end

  def test_results_are_decoded_into_ruby_values
    replies = [
      { "Json" => { "count" => 2, "members" => [{ "member" => [97], "score" => 1.5 }, [98]] } },
      { "Json" => { "state" => "fresh", "valueHex" => "009f" } },
      { "CacheValues" => [[108], [97]] },
      { "CacheValues" => [nil, nil] }
    ]
    script = lambda do |peer|
      peer.handshake
      replies.each do |data|
        peer.read
        peer.send_frame(TriCoreDB::Frame::RESPONSE, { "request_id" => "r", "status" => "ok", "data" => data })
      end
      begin
        peer.read
      rescue StandardError, IOError
        nil
      end
    end

    ScriptedPeer.run(script) do |db|
      assert_equal [["a", 1.5], "b"], db.cache_zrange("n", "z", 0, -1)
      assert_equal "\x00\x9F".b, db.cache_get_fresh("n", "k", "me", 1000)["value"]
      assert_equal %w[l a], db.cache_blpop("n", ["l"], 10)
      assert_nil db.cache_brpop("n", ["l"], 10)
    end
  end

  def test_an_unbounded_score_range_is_sent_as_the_largest_finite_number
    assert_equal({ "value" => Float::MAX, "exclusive" => false }, TriCoreDB::ScoreBound.highest)
    assert_equal({ "value" => -Float::MAX, "exclusive" => false }, TriCoreDB::ScoreBound.inclusive(-Float::INFINITY))
    assert_raises(ArgumentError) { TriCoreDB::ScoreBound.inclusive(Float::NAN) }
  end
